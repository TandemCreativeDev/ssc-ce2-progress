#!/usr/bin/env python3
"""Pull tracked time for the SSC CE2 project from Solidtime and write index.html.

The page is fully static - the token stays in the environment and only day
figures reach the HTML. Day caps come from each task's estimated_time in
Solidtime; the budget is their sum. Tasks without an estimate still get a
row, showing tracked time only.

Usage:
  set -a && . ./.env && set +a
  python3 scripts/gen_progress.py

Standard library only.
"""
import html
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime
from zoneinfo import ZoneInfo

BASE_URL = os.environ.get("SOLIDTIME_URL", "https://solidtime.zestdev.uk")
TOKEN = os.environ.get("SOLIDTIME_TOKEN", "")
PROJECT_NAME = "SSC CE2"
PREFIX = "SSC CE2 - "
HOURS_PER_DAY = 7.5

# Tasks left off the page. Their time still counts towards the total.
HIDDEN = set()

# Display names on the page, keyed by task name with the prefix already
# stripped.
LABELS = {}
OUT = os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), "index.html")


def api(path, params=None):
    if not TOKEN:
        sys.exit("SOLIDTIME_TOKEN is not set.")
    url = BASE_URL.rstrip("/") + "/api" + path
    if params:
        url += "?" + urllib.parse.urlencode(params, doseq=True)
    req = urllib.request.Request(url, headers={
        "Authorization": "Bearer " + TOKEN,
        "Accept": "application/json",
        # Cloudflare in front of Solidtime 403s the default urllib agent.
        "User-Agent": "ssc-ce2-progress-page",
    })
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.load(r)["data"]
    except urllib.error.HTTPError as e:
        sys.exit("HTTP %d on %s\n%s" % (e.code, path, e.read()[:300]))


def days(seconds):
    return seconds / 3600.0 / HOURS_PER_DAY


def fmt(value):
    return ("%.1f" % value).rstrip("0").rstrip(".")


def main():
    org = os.environ.get("SOLIDTIME_ORG") or \
        api("/v1/users/me/memberships")[0]["organization"]["id"]
    projects = api("/v1/organizations/%s/projects" % org)
    project = next((p for p in projects if p["name"] == PROJECT_NAME), None)
    if not project:
        sys.exit("No project named %r" % PROJECT_NAME)

    # done=all so finished tasks still resolve to a name.
    tasks = api("/v1/organizations/%s/tasks" % org, {"done": "all"})
    result = api("/v1/organizations/%s/time-entries/aggregate" % org,
                 {"group": "task", "project_ids[]": project["id"]})
    seconds = {r["key"]: r["seconds"] for r in result["grouped_data"] or []}

    # Every task in the project gets a row, in name order, even before time
    # is logged on it. The cap is the task's estimated_time, if set.
    rows = sorted(
        ((t["name"], days(seconds.get(t["id"], 0)),
          days(t["estimated_time"]) if t["estimated_time"] else None)
         for t in tasks if t["project_id"] == project["id"]
         and t["name"] not in HIDDEN),
        key=lambda row: row[0])
    if seconds.get(None):
        rows.append(("Other", days(seconds[None]), None))
    tracked = days(result["seconds"] or 0)
    budget = sum(cap for _, _, cap in rows if cap)

    write_page(tracked, budget, rows)
    print("tracked %s / %s days" % (fmt(tracked), fmt(budget)))
    for name, d, cap in rows:
        print("  %-30s %s%s" % (name, fmt(d),
                                " / %s" % fmt(cap) if cap else ""))


def label(name):
    name = name.removeprefix(PREFIX)
    return LABELS.get(name, name)


def bar(value, total):
    pct = min(100, value / total * 100) if total else 0
    # GOV.UK error red once a task is over its estimate.
    over = ' class="over"' if total and value > total else ""
    return '<div class="bar"><span%s style="width:%.1f%%"></span></div>' \
        % (over, pct)


def write_page(tracked, budget, rows):
    updated = datetime.now(ZoneInfo("Europe/London")).strftime(
        "%-d %b %Y, %H:%M %Z")
    headline = "%s of %s days used" % (fmt(tracked), fmt(budget))
    sub = "%s days remaining" % fmt(max(0, budget - tracked))
    task_rows = "\n".join(
        '<li><div class="row"><span>%s</span><b>%s <i>%s</i></b></div>%s</li>'
        % (html.escape(label(name)), fmt(d),
           "/ %s d" % fmt(cap) if cap else "d", bar(d, cap or tracked))
        for name, d, cap in rows)

    page = TEMPLATE.format(headline=headline, sub=sub, updated=updated,
                           total_bar=bar(tracked, budget),
                           rows=task_rows)
    with open(OUT, "w") as f:
        f.write(page)


